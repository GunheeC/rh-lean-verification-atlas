"""Render the bilingual readers and the paper section from data/glance_guide.json."""
from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
NOTICE = 'AI-written, AI cross-reviewed; no human sign-off; not a claim that RH is proved'
CLASSES = {'written': 'fill:#fff,stroke:#222',
           'outlined': 'fill:#ddd,stroke:#222,stroke-dasharray:5 3',
           'lean': 'fill:#aaa,stroke:#222,stroke-width:2px'}


def weight(data, language):
    values = {uid: lines for uid, lines, *_ in data['sizes']}
    both = values['P013'] + values['T02']
    total = data['total_lines']
    return data['weight'][language].format(both=f'{both:,}', total=f'{total:,}', percent=f'{100*both/total:.2f}')


def mermaid(data, language):
    names = {step['id']: f'{i} {step["node"][language]}' for i, step in enumerate(data['steps'], 1)}
    seen = set()

    def node(key):
        if key in seen:
            return key
        seen.add(key)
        return f'{key}["{names[key]}"]'

    lines = ['```mermaid', 'flowchart TD']
    lines.extend('    ' + node(left) + ' --> ' + node(right) for left, right in data['edges'])
    lines.extend(f'    classDef {status} {style}' for status, style in CLASSES.items())
    for status in ('outlined', 'lean', 'written'):
        keys = ','.join(step['id'] for step in data['steps'] if step['status'] == status)
        lines.append(f'    class {keys} {status}')
    return '\n'.join([*lines, '```'])


def tikz(data):
    # Steps 1–3 share the first row. V enters the host from its right; host and F feed the join.
    positions = [(0, 0), (5, 0), (10, 0), (5, -3.2), (5, -6), (5, -8.8), (5, -11.6), (5, -14.4)]
    lines = [r'''\begin{figure}[p]
\centering
\begin{tikzpicture}[x=1cm,y=1.12cm,>=Stealth,
  base/.style={draw=black!80,inner xsep=4pt,inner ysep=8pt,align=center,font=\small},
  lean/.style={base,fill=black!32,line width=1.1pt},
  outlined/.style={base,fill=black!12,dashed,line width=.7pt},
  written/.style={base,fill=white,line width=.6pt},
  stepedge/.style={->,line width=.8pt,draw=black!85}]''']
    for i, (step, (x, y)) in enumerate(zip(data['steps'], positions, strict=True), 1):
        width = '3.78' if i <= 3 else '7.5'
        lines.append(rf'\node[{step["status"]},text width={width}cm] ({step["id"]}) at ({x},{y}) {{\textbf{{{i}. {step["node"]["en"]}}}}};')
    for src, dst in data['edges']:
        origin, target = src, dst
        if (src, dst) == ('V', 'H'):
            origin, target = 'V.west', 'H.east'
        elif dst == 'J':
            origin = src + '.south'
            target = dst + ('.north west' if src == 'H' else '.north east')
        lines.append(rf'\draw[stepedge] ({origin})--({target});')
    lines += [r'\end{tikzpicture}', r'\caption{' + data['legend']['en'] + r'}\label{fig:v7-glance}', r'\end{figure}']
    return '\n'.join(lines)


def tex_unit(uid):
    if uid.startswith('P'):
        return r'\nodeid{' + uid + '}'
    if uid.startswith('D'):
        return rf'\hyperref[decomp:{uid}]{{{uid}}}'
    target = 'r24:intro' if uid == 'V4-COND' else f'sub:{uid}'
    return rf'\hyperref[{target}]{{{uid}}}'


def render_tex(data):
    # §2 prose contains ordinary Unicode and delimited TeX mathematics; percentages need escaping.
    t = lambda key: data[key]['en']
    blocks = [r'% Generated by scripts/glance_guide.py from data/glance_guide.json.',
              r'\newcommand{\glancestep}[1]{\par\addvspace{.7\baselineskip}\noindent\textbf{#1}\par\nobreak\noindent\ignorespaces}',
              r'\section{' + t('section') + r'}\label{sec:proof-glance}',
              r'\noindent\textbf{' + t('opening_title') + '.} ' + '\n'.join(t('opening')),
              t('background') + r'~\cite{' + data['reference']['key'] + '}.', t('orientation')]
    for i, step in enumerate(data['steps'], 1):
        if i == 5:
            blocks.extend([r'\clearpage', t('analytic_note')])
        details = r'(Details: \S\ref{' + step['section'] + '}, ' + ', '.join(map(tex_unit, step['units'])) + '.)'
        blocks.append(r'\glancestep{' + f'{i}. ' + step['heading']['en'] + '}\n' + '\n'.join(step['sentences']['en']) + ' ' + details)
    blocks.extend([r'\clearpage', tikz(data), r'\clearpage',
                   r'\noindent\fbox{\begin{minipage}{\dimexpr\linewidth-2\fboxsep-2\fboxrule\relax}\textbf{' + t('weight_title') + '.} ' + weight(data, 'en').replace('%', r'\%') + r'\end{minipage}}'])
    rows = [r'\begin{table}[ht]\centering\small', r'\caption{' + t('table_title') + r'}\label{tab:v7-scale}',
            r'\begin{tabularx}{\linewidth}{@{}>{\raggedright\arraybackslash}Xr>{\raggedright\arraybackslash}p{.27\linewidth}@{}}',
            r'\toprule Block and declaration & Dominated Lean lines & Selected reading in v8\\\midrule']
    for uid, count, start, end, label in data['sizes']:
        lines = f'{count:,}' if count is not None else '---'
        a, b = r'\pageref{' + start + '}', r'\pageref{' + end + '}'
        count_pages = r'\number\numexpr\getpagerefnumber{' + end + r'}-\getpagerefnumber{' + start + r'}+1\relax'
        span = rf'\ifnum\getpagerefnumber{{{start}}}=\getpagerefnumber{{{end}}} p.~{a} (1 page)\else pp.~{a}--{b} ({count_pages}~pages)\fi'
        rows.append(f'{label["en"]} ({tex_unit(uid)}) & {lines} & {span}' + r'\\')
    rows.extend([r'\bottomrule\end{tabularx}', r'\end{table}'])
    blocks.extend(['\n'.join(rows), t('count_explanation'), r'\glancestep{' + t('closing_title') + '}\n' + t('closing'), r'\phantomsection\label{v7:glance-end}'])
    return '\n\n'.join(blocks) + '\n'


def render_markdown(data, language, locators):
    en = language == 'en'
    prefix = '../' if en else '../../'
    t = lambda key: data[key][language]
    pdf = prefix + 'editions/v0.1.0/paper_v8.pdf'

    def link(label, path):
        return f'[{label}]({path})'

    def section(key):
        num = locators['section_numbers'][key]
        text = ('§' + str(num)) if en else (str(num) + '절' if str(num)[0].isdigit() else '부록 ' + str(num))
        return link(text, pdf + '#page=' + str(locators['named_destinations'][key]['pdf_page']))

    def unit(uid):
        return link(uid, prefix + 'units/' + uid + '.md')

    ref = data['reference']
    bibliog = f'{ref["author"]}, *{ref["title"]}*, arXiv:{ref["arxiv"]}'
    background = t('background') + ' ' + link(bibliog, 'https://arxiv.org/abs/' + ref['arxiv']) + '.'
    route = ' · '.join([section('sec:proof-glance'), link('Five precise statements' if en else '정확한 다섯 명제', prefix + 'sources/lean-goals.md'),
                        link('한국어', 'ko/proof-at-a-glance.md') if en else link('English', '../proof-at-a-glance.md')])
    blocks = ['# ' + t('section'), NOTICE, '**' + t('opening_title') + '.** ' + ' '.join(t('opening')), background, route,
              '## ' + ('Eight steps' if en else '여덟 단계'), t('orientation')]
    for i, step in enumerate(data['steps'], 1):
        more = [section(step['section']), *map(unit, step['units'])]
        if step['id'] in ('V', 'F'):
            more.append(link((step['id'] + ' reading map') if en else (step['id'] + ' 읽기 지도'), (prefix if en else '') + 'pillars/' + step['id'] + '.md'))
        label = 'Details' if en else '자세히'
        blocks.append(f'{i}. **{step["heading"][language]}** ' + ' '.join(step['sentences'][language]) + f' ({label}: ' + ' · '.join(more) + ')')
    blocks.extend([t('analytic_note'), '## ' + ('Which steps use which inputs?' if en else '어느 단계가 어디에 쓰이는가?'), t('legend'), mermaid(data, language),
                   '> **' + t('weight_title') + '.** ' + weight(data, language), '## ' + t('table_title')])
    table = ['| Block and declaration | Dominated Lean lines | Selected paper v8 passage |' if en else '| 부분과 선언 | 지배하는 Lean 줄 수 | 논문 v8의 읽기 구간 |', '|---|---:|---|']
    for uid, count, start, end, label in data['sizes']:
        lines = f'{count:,}' if count is not None else '—'
        a, b = (locators['printed_pages'][key] for key in (start, end))
        first, last = (locators['named_destinations'][key]['pdf_page'] for key in (start, end))
        if a == b:
            pages = link(f'p. {a} (1 page)' if en else f'{a}쪽 (1쪽)', f'{pdf}#page={first}')
        else:
            ends = link(str(a), f'{pdf}#page={first}') + '–' + link(str(b), f'{pdf}#page={last}')
            pages = (f'pp. {ends} ({b-a+1} pages)' if en else f'{ends}쪽 ({b-a+1}쪽)')
        table.append(f'| {label[language]} · {unit(uid)} | {lines} | {pages} |')
    blocks.extend(['\n'.join(table), t('count_explanation') + ' ' + link('Counting method' if en else '집계 방법', prefix + 'sources/coverage.md') + ' · ' + link('Disjoint regions' if en else '겹치지 않는 영역', prefix + 'progress/README.md'),
                   '## ' + t('closing_title'), t('closing') + ' ' + link('External audit' if en else '외부 검사', prefix + 'sources/kernel-audit.md') + ' · ' + link('Status' if en else '검토 현황', '../STATUS.md' if en else 'STATUS.md') + ' · ' + link('Edition register' if en else '판본 장부', prefix + 'data/editions.json')])
    return '\n\n'.join(blocks) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true', help='Compare files with canonical output without writing them.')
    parser.add_argument('--tex', type=Path, help='Also write or check the actual paper build input.')
    parser.add_argument('--tex-only', action='store_true', help='Render before the new PDF pagination exists; requires --tex.')
    args = parser.parse_args()
    if args.tex_only and args.tex is None:
        parser.error('--tex-only needs --tex')
    data_dir = args.root / 'data'
    data = json.loads((data_dir / 'glance_guide.json').read_text(encoding='utf-8'))
    tex = render_tex(data)
    output = {}
    if args.tex:
        output[args.tex] = tex
    if not args.tex_only:
        edition = json.loads((data_dir / 'editions.json').read_text(encoding='utf-8'))['editions']['paper2_v8']
        digest = sha256(tex.encode()).hexdigest()
        if edition['new_reader_exposition']['section_tex_sha256'] != digest:
            sys.exit('The generated TeX differs from the paper section recorded for v8.')
        records = json.loads((args.root / edition['coverage_label_index']).read_text(encoding='utf-8'))
        if records['source_pdf_sha256'] != edition['sha256']:
            sys.exit('The reading destinations belong to a different PDF.')
        for language, path in [('en', 'docs/proof-at-a-glance.md'), ('ko', 'docs/ko/proof-at-a-glance.md')]:
            output[args.root / path] = render_markdown(data, language, records)
    mismatches = []
    for path, content in output.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content.encode():
                mismatches.append(str(path))
        else:
            path.write_bytes(content.encode())
    if mismatches:
        sys.exit('Glance guide differs from source: ' + ', '.join(mismatches))
    print(f'{"Checked" if args.check else "Rendered"} {len(output)} glance guide files.')


if __name__ == '__main__':
    main()
